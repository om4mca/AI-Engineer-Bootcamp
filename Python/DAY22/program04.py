numbers = [25, 10, 85, 40, 5, 60]


max_val = max(numbers)
min_val = min(numbers)

print(f"Maximum Value: {max_val}")  # Output: Maximum Value: 85
print(f"Minimum Value: {min_val}")  # Output: Minimum Value: 5