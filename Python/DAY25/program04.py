import numpy as np

# 1. Minimum and Maximum in a 1D Array
arr_1d = np.array([45, 12, 89, 3, 67, 23])

min_val = np.min(arr_1d)
max_val = np.max(arr_1d)

print("1D Array:", arr_1d)
print("Minimum Value:", min_val)
print("Maximum Value:", max_val)