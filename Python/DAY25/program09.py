import numpy as np

# 1. Cumulative Sum of a 1D Array
arr_1d = np.array([10, 20, 30, 40, 50])
cumsum_1d = np.cumsum(arr_1d)

print("1D Array:", arr_1d)
print("Cumulative Sum:", cumsum_1d)