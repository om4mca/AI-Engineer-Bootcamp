import numpy as np

# ==========================================
# 1. 1D Array Sum and Mean
# ==========================================
arr_1d = np.array([10, 20, 30, 40, 50])

print("--- 1D Array ---")
print("Array     :", arr_1d)
print("Total Sum :", np.sum(arr_1d))  # 10 + 20 + 30 + 40 + 50 = 150
print("Mean      :", np.mean(arr_1d)) # 150 / 5 = 30.0


